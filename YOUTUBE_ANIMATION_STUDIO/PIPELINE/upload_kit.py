"""Build the upload kit for every QC-passed Short (never for unfinished ones).

Writes FINAL_VIDEOS/<ID>.srt (sentence-level subtitles from the real narration timings; upload it next to the video so
YouTube has an accurate caption track in addition to the burned-in captions) and FINAL_VIDEOS/UPLOAD_KIT.md (per video: files,
titles and description copied verbatim from THUMBNAILS/<ID>/PACKAGING.md, thumbnail files, and the pre-upload checks found in
QUALITY_CONTROL/<ID>/FACTCHECK.md).
Usage: python3 PIPELINE/upload_kit.py
"""
import glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def P(*a):
    return os.path.join(ROOT, *a)


def ts(t):
    t = max(0.0, t)
    h, m, s = int(t // 3600), int(t % 3600 // 60), t % 60
    return f"{h:02d}:{m:02d}:{int(s):02d},{int(round((s - int(s)) * 1000)):03d}"


def srt_for(id_):
    tm = json.load(open(P("AUDIO", id_, "timings.json")))
    cues = []
    for ln in tm["lines"]:
        cur = []
        for w in ln["words"]:
            cur.append(w)
            if re.search(r"[\.\?\!:]$", w["w"]) or len(cur) >= 12:
                cues.append(cur)
                cur = []
        if cur:
            cues.append(cur)
    out = []
    for i, c in enumerate(cues):
        start = c[0]["start"]
        end = c[-1]["end"] + 0.12
        if i + 1 < len(cues):
            end = min(end, cues[i + 1][0]["start"] - 0.02)
        end = max(end, start + 0.3)
        out.append(f"{i + 1}\n{ts(start)} --> {ts(end)}\n{' '.join(w['w'] for w in c)}\n")
    path = P("FINAL_VIDEOS", f"{id_}.srt")
    open(path, "w").write("\n".join(out))
    return path, len(cues)


def section(md, heading_regex):
    """Return the body of the first markdown section whose heading matches (up to the next heading of the same/higher level)."""
    lines = md.splitlines()
    for i, l in enumerate(lines):
        m = re.match(r"^(#+)\s+(.*)$", l)
        if m and re.search(heading_regex, m.group(2), re.I):
            lvl = len(m.group(1))
            body = []
            for l2 in lines[i + 1:]:
                m2 = re.match(r"^(#+)\s+", l2)
                if m2 and len(m2.group(1)) <= lvl:
                    break
                body.append(l2)
            return "\n".join(body).strip()
    return ""


def main():
    done = []
    for qc in sorted(glob.glob(P("QUALITY_CONTROL", "*", "QC_REPORT.md"))):
        id_ = qc.split(os.sep)[-2]
        if "VERDICT: PASS" in open(qc).read() and os.path.exists(P("FINAL_VIDEOS", f"{id_}.mp4")):
            done.append(id_)
    out = ["# UPLOAD KIT — finished, QC-passed Shorts", "",
           "Generated by `PIPELINE/upload_kit.py` from files on disk. Only videos whose `QC_REPORT.md` says `VERDICT: PASS` are listed.",
           "Narration has not been auditioned by ear inside the build container — listen once before publishing.", ""]
    for id_ in done:
        sc = json.load(open(P("SCRIPTS", id_, "script.json")))
        srt, n = srt_for(id_)
        pk_path = P("THUMBNAILS", id_, "PACKAGING.md")
        pk = open(pk_path).read() if os.path.exists(pk_path) else ""
        thumbs = sorted(os.path.relpath(t, ROOT) for t in glob.glob(P("THUMBNAILS", id_, "thumb_[A-Z].png")))
        fc_path = P("QUALITY_CONTROL", id_, "FACTCHECK.md")
        checks = []
        if os.path.exists(fc_path):
            for l in open(fc_path).read().splitlines():
                if re.search(r"before (upload|publish)|re-?check|recheck|status checked", l, re.I):
                    checks.append(l.strip().lstrip("-* ").strip()[:400])
        mp4 = P("FINAL_VIDEOS", f"{id_}.mp4")
        out += [f"## {id_} — {sc.get('title', '')}", "",
                f"- Video: `FINAL_VIDEOS/{id_}.mp4` ({os.path.getsize(mp4) / 1e6:.0f} MB) · Subtitles: `FINAL_VIDEOS/{id_}.srt` ({n} cues)",
                f"- Thumbnails: {', '.join('`' + t + '`' for t in thumbs) if thumbs else 'not made yet'}",
                f"- QC: `QUALITY_CONTROL/{id_}/QC_REPORT.md` · Fact-check: `QUALITY_CONTROL/{id_}/FACTCHECK.md`", ""]
        t = section(pk, r"^titles")
        if t:
            out += ["### Titles", "", t, ""]
        d = section(pk, r"description")
        if d:
            out += ["### Description", "", d, ""]
        f = section(pk, r"final thumbnails")
        if f:
            pick = [l for l in f.splitlines() if re.search(r"recommended pick", l, re.I)]
            if pick:
                out += ["### Thumbnail pick", "", pick[0], ""]
        if checks:
            out += ["### Check before upload", ""] + [f"- {c}" for c in checks[:8]] + [""]
    open(P("FINAL_VIDEOS", "UPLOAD_KIT.md"), "w").write("\n".join(out) + "\n")
    print("upload kit:", done)


if __name__ == "__main__":
    main()
